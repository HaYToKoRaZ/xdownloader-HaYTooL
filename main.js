let currentLang = localStorage.getItem('haytool_lang') || 'tr';
let currentTheme = localStorage.getItem('haytool_theme') || 'dark';

function applyTheme(theme) {
  document.documentElement.setAttribute('data-theme', theme);
  const themeIcon = document.getElementById('themeIcon');
  if (themeIcon) {
    themeIcon.textContent = theme === 'dark' ? '☀️' : '🌙';
  }
  localStorage.setItem('haytool_theme', theme);
}

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('haytool_lang', lang);
  const t = translations[lang] || translations.tr;

  const langFlag = document.getElementById('langFlag');
  const langLabel = document.getElementById('langLabel');
  if (langFlag) langFlag.textContent = t.flag;
  if (langLabel) langLabel.textContent = t.label;

  // Update page title if key exists
  if (t.pageTitle) document.title = t.pageTitle;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.textContent = t[key];
    }
  });

  // Update html lang attribute
  document.documentElement.setAttribute('lang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
  applyTheme(currentTheme);
  applyLang(currentLang);

  // Theme Toggle
  const themeBtn = document.getElementById('themeToggle');
  if (themeBtn) {
    themeBtn.addEventListener('click', () => {
      const nextTheme = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
      applyTheme(nextTheme);
    });
  }

  // Lang Picker
  const langBtn = document.getElementById('langBtn');
  const langDropdown = document.getElementById('langDropdown');

  if (langBtn && langDropdown) {
    langBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      langDropdown.classList.toggle('hidden');
    });

    document.querySelectorAll('.lang-item').forEach(item => {
      item.addEventListener('click', () => {
        const lang = item.getAttribute('data-lang');
        applyLang(lang);
        langDropdown.classList.add('hidden');
      });
    });

    document.addEventListener('click', () => {
      langDropdown.classList.add('hidden');
    });
  }

  // FAQ accordion (CSS-only fallback + JS enhancement)
  document.querySelectorAll('.faq-question').forEach(q => {
    q.addEventListener('click', () => {
      const item = q.closest('.faq-item');
      const isOpen = item.classList.contains('open');
      document.querySelectorAll('.faq-item').forEach(i => i.classList.remove('open'));
      if (!isOpen) item.classList.add('open');
    });
  });
});